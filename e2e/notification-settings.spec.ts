import { expect, login, seedOwnerHousehold, test } from "./support/fixtures";
import { createManualTask } from "../src/lib/d1/todos";
test("個人の通知設定を保存し、候補の休止と解除で共有予定を変えない", async ({ page, db }, testInfo) => {
  await seedOwnerHousehold(db);
  await createManualTask(db, { userId: "owner" }, { title: "通知を休む点検", managedItemId: null });
  await db.prepare("UPDATE task_occurrences SET must_complete_by='2026-01-01'").run();
  await page.setViewportSize({ width: 390, height: 844 });
  await login(page);
  await page.goto("/settings/integrations");
  await page.getByRole("link", { name: "通知設定と配信履歴" }).click();
  await expect(page.getByRole("heading", { name: "あなたの通知設定" })).toBeVisible();
  await expect(page.getByLabel("通知を有効にする")).not.toBeChecked();
  await page.getByLabel("まとめる時刻").fill("10:30");
  await page.getByRole("button", { name: "通知設定を保存" }).click();
  await expect(page.getByRole("status").filter({ hasText: "通知設定を保存しました" })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("まとめる時刻")).toHaveValue("10:30");
  await page.getByRole("button", { name: "明日のまとめ時刻まで休む" }).click();
  await expect(page.getByText(/まで通知を休止$/)).toBeVisible();
  await page.getByRole("button", { name: "休止を解除", exact: true }).click();
  await expect(page.getByText(/まで通知を休止$/)).toHaveCount(0);
  await page.getByRole("button", { name: "この用事の通知を休止", exact: true }).click();
  await expect(page.getByText("この用事の通知を休止中")).toBeVisible();
  await expect(page.getByText("配信履歴はまだありません。")).toBeVisible();
  const rows = await db.prepare("SELECT must_complete_by FROM task_occurrences").all<{ must_complete_by: string }>();
  expect(rows.results.every((row) => row.must_complete_by === "2026-01-01")).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("notification-settings-mobile.png"), fullPage: true });
});
