import { expect, login, seedOwnerHousehold, test } from "./support/fixtures";
import { createConsumable } from "../src/lib/d1/consumables";
test.use({ viewport: { width: 390, height: 844 } });
test("在庫観測・補充・日付訂正を区別し、モバイルで原記録と訂正履歴を確認できる", async ({ db, page }, testInfo) => {
  await seedOwnerHousehold(db);
  const id = await createConsumable(db, { userId: "owner" }, { name: "履歴を試す洗剤", externalUrl: null, note: null, productCode: null, managedItemIds: [], taskRuleIds: [] });
  await login(page);
  await page.goto(`/consumables/${id}`);
  await page.getByRole("button", { name: "ない", exact: true }).click();
  await expect(page.getByText("現在: ない", { exact: true })).toBeVisible();
  expect((await db.prepare("SELECT * FROM consumable_refills WHERE consumable_id=?").bind(id).all()).results).toHaveLength(0);
  await page.getByRole("button", { name: "補充した", exact: true }).click();
  await expect(page.getByText("現在: ある", { exact: true })).toBeVisible();
  const original = await db.prepare("SELECT id,refilled_on FROM consumable_refills WHERE consumable_id=?").bind(id).first<{ id: string; refilled_on: string }>();
  if (!original) throw new Error("補充記録がありません");
  await page.getByRole("button", { name: "少ない", exact: true }).click();
  await expect(page.getByText("現在: 少ない", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "在庫・補充の履歴と訂正" }).click();
  await expect(page.getByRole("heading", { name: "履歴を試す洗剤の在庫・補充履歴" })).toBeVisible();
  const refill = page.getByRole("listitem").filter({ has: page.getByText(/^補充:/) });
  await refill.getByRole("link", { name: "記録と訂正履歴を開く" }).click();
  await expect(page).toHaveURL(/history\?record=/);
  await page.getByText("この記録を訂正・取消する", { exact: true }).click();
  await page.getByLabel("正しい実施日", { exact: true }).fill("2026-01-01");
  await page.getByRole("button", { name: "訂正を保存", exact: true }).click();
  await expect(page.getByText(/訂正（版1）/)).toBeVisible();
  await expect(page.getByText(/原記録（版0）/)).toBeVisible();
  expect(await db.prepare("SELECT refilled_on FROM consumable_refills WHERE id=?").bind(original.id).first()).toEqual({ refilled_on: original.refilled_on });
  await page.goto(`/consumables/${id}`);
  await expect(page.getByText("現在: 少ない", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "在庫・補充の履歴と訂正" }).click();
  await page.getByRole("listitem").filter({ has: page.getByText(/^補充:/) }).getByRole("link", { name: "記録と訂正履歴を開く" }).click();
  await expect(page).toHaveURL(/history\?record=/);
  const change = page.getByRole("combobox", { name: "訂正する項目", exact: true });
  if (!await change.isVisible()) await page.getByText("この記録を訂正・取消する", { exact: true }).click();
  await expect(change).toBeVisible();
  await change.selectOption("void");
  await page.getByRole("button", { name: "訂正を保存", exact: true }).click();
  await expect(page.getByText(/取消（版2）/)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => { window.scrollTo({ top: 0, behavior: "instant" }); });
  await page.screenshot({ path: testInfo.outputPath("stock-corrections-mobile.png"), fullPage: true });
});
